/**
 * @jest-environment node
 *
 * Database integration test for
 * 20261123_rc059_articles_title_optional_for_drafts.sql.
 *
 * Runs only against a LOCAL, disposable Postgres:
 *
 *   SERIES_DB_TEST_URL=postgresql://postgres:<pw>@127.0.0.1:<port>/postgres
 *
 * Skipped without SERIES_DB_TEST_URL; any non-local host is refused. Every
 * test runs inside a transaction that is rolled back, on a stand-in
 * public.articles table created inside that transaction, so nothing persists
 * and no other suite's tables are touched.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { Client } from 'pg';

const DB_URL = process.env.SERIES_DB_TEST_URL;
const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1', '::1', '[::1]']);

const MIGRATION = readFileSync(
  path.join(
    process.cwd(),
    'supabase/migrations/20261123_rc059_articles_title_optional_for_drafts.sql',
  ),
  'utf8',
)
  // The test supplies the transaction (and rolls it back).
  .replace(/^\s*begin;\s*$/m, '')
  .replace(/^\s*commit;\s*$/m, '');

/**
 * The columns the migration touches, as production has them before it:
 * title NOT NULL, status nullable with a default.
 */
const BEFORE = `
  drop table if exists public.articles cascade;
  create table public.articles (
    id bigint generated by default as identity primary key,
    slug text not null unique,
    title text not null,
    status text default 'draft'
  );
`;

const describeDb = DB_URL ? describe : describe.skip;
jest.setTimeout(30_000);

describeDb('rc059: articles.title optional for drafts (local database)', () => {
  let db: Client;
  let n = 0;

  beforeAll(async () => {
    if (!LOCAL_HOSTS.has(new URL(DB_URL!).hostname)) {
      throw new Error('Refusing to run database tests against a non-local host');
    }
    db = new Client({ connectionString: DB_URL });
    await db.connect();
  });

  afterAll(async () => {
    await db?.end();
  });

  async function inRolledBackTx(fn: () => Promise<void>) {
    await db.query('begin');
    try {
      await fn();
    } finally {
      await db.query('rollback');
    }
  }

  /** Runs a statement; resolves the SQLSTATE on failure, or null on success. */
  async function attempt(sql: string, params?: unknown[]): Promise<string | null> {
    const sp = `sp_${n++}`;
    await db.query(`savepoint ${sp}`);
    try {
      await db.query(sql, params);
      await db.query(`release savepoint ${sp}`);
      return null;
    } catch (error) {
      await db.query(`rollback to savepoint ${sp}`);
      return (error as { code?: string }).code ?? 'unknown';
    }
  }

  const insert = (slug: string, title: string | null, status: string | null) =>
    attempt('insert into public.articles (slug, title, status) values ($1, $2, $3)', [
      slug,
      title,
      status,
    ]);

  it('applies over existing rows without changing them, and is re-runnable', () =>
    inRolledBackTx(async () => {
      await db.query(BEFORE);
      await db.query(
        `insert into public.articles (slug, title, status) values
           ('live', 'Live', 'published'), ('wip', 'Draft', 'draft'), ('old', 'Old', null)`,
      );
      await db.query(MIGRATION);
      await db.query(MIGRATION);

      const { rows } = await db.query(
        'select slug, title, status from public.articles order by id',
      );
      expect(rows).toEqual([
        { slug: 'live', title: 'Live', status: 'published' },
        { slug: 'wip', title: 'Draft', status: 'draft' },
        { slug: 'old', title: 'Old', status: null },
      ]);
      const { rows: constraint } = await db.query(
        `select convalidated from pg_constraint
          where conname = 'articles_title_required_unless_draft'`,
      );
      expect(constraint).toEqual([{ convalidated: true }]);
    }));

  it('lets a draft have no English title, or a blank one', () =>
    inRolledBackTx(async () => {
      await db.query(BEFORE);
      await db.query(MIGRATION);
      expect(await insert('greek-first', null, 'draft')).toBeNull();
      expect(await insert('blank', '  ', 'draft')).toBeNull();
    }));

  it.each(['published', 'scheduled', 'review', 'archived'])(
    'still requires a non-blank title for %s rows',
    status =>
      inRolledBackTx(async () => {
        await db.query(BEFORE);
        await db.query(MIGRATION);
        expect(await insert(`${status}-null`, null, status)).toBe('23514');
        expect(await insert(`${status}-blank`, ' ', status)).toBe('23514');
        expect(await insert(`${status}-ok`, 'Title', status)).toBeNull();
      }),
  );

  it('treats a NULL status as not a draft', () =>
    inRolledBackTx(async () => {
      await db.query(BEFORE);
      await db.query(MIGRATION);
      expect(await insert('no-status', null, null)).toBe('23514');
    }));

  it('refuses to publish a title-less draft until it gets a title', () =>
    inRolledBackTx(async () => {
      await db.query(BEFORE);
      await db.query(MIGRATION);
      await db.query(
        "insert into public.articles (slug, title, status) values ('d', null, 'draft')",
      );
      expect(
        await attempt("update public.articles set status = 'published' where slug = 'd'"),
      ).toBe('23514');
      expect(
        await attempt(
          "update public.articles set status = 'published', title = 'Now' where slug = 'd'",
        ),
      ).toBeNull();
      expect(await attempt("update public.articles set title = null where slug = 'd'")).toBe(
        '23514',
      );
    }));

  it('fails as a whole when an existing non-draft row has a blank title (what the preflight reports)', () =>
    inRolledBackTx(async () => {
      await db.query(BEFORE);
      await db.query(
        "insert into public.articles (slug, title, status) values ('bad', '', 'published')",
      );
      expect(await attempt(MIGRATION)).toBe('23514');
      // Nothing was applied: the column is still NOT NULL.
      const { rows } = await db.query(
        `select is_nullable from information_schema.columns
          where table_schema = 'public' and table_name = 'articles' and column_name = 'title'`,
      );
      expect(rows).toEqual([{ is_nullable: 'NO' }]);
    }));

  it('rolls back as documented once no draft is left without a title', () =>
    inRolledBackTx(async () => {
      await db.query(BEFORE);
      await db.query(MIGRATION);
      await db.query(
        "insert into public.articles (slug, title, status) values ('d', null, 'draft')",
      );
      const rollback = `
        alter table public.articles drop constraint if exists articles_title_required_unless_draft;
        alter table public.articles alter column title set not null;`;
      // Blocked while a title-less draft exists...
      expect(await attempt(rollback)).toBe('23502');
      await db.query("update public.articles set title = 'Named' where slug = 'd'");
      // ...and clean afterwards.
      expect(await attempt(rollback)).toBeNull();
    }));
});
