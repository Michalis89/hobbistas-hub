-- Series membership is deliberately separate from articles. Deleting a series
-- never deletes its articles. Chapter writes go through one transactional RPC.
create table public.article_series (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text not null check (length(trim(title)) > 0),
  description text,
  cover_image text,
  status text not null default 'draft' check (status in ('draft', 'published')),
  owner_id uuid references public.users(id) on delete set null,
  version bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.article_series_translations (
  series_id bigint not null references public.article_series(id) on delete cascade,
  locale text not null check (locale = 'el'),
  title text not null check (length(trim(title)) > 0),
  description text,
  primary key (series_id, locale)
);

create table public.article_series_chapters (
  series_id bigint not null references public.article_series(id) on delete cascade,
  article_id bigint not null unique references public.articles(id) on delete cascade,
  position integer not null check (position > 0),
  primary key (series_id, article_id),
  unique (series_id, position)
);

create function public.series_is_elevated() returns boolean
language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.users where id = auth.uid()
  and roles && array['admin','owner','moderator']::text[]) $$;

create function public.series_can_manage(p_series_id bigint) returns boolean
language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.article_series s where s.id = p_series_id
  and (s.owner_id = auth.uid() or public.series_is_elevated())) $$;

create function public.series_is_public(p_series_id bigint) returns boolean
language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.article_series s
  join public.article_series_chapters c on c.series_id = s.id
  join public.articles a on a.id = c.article_id
  where s.id = p_series_id and s.status = 'published' and a.status = 'published'
  and (a.published_at is null or a.published_at <= now())) $$;

alter table public.article_series enable row level security;
alter table public.article_series_translations enable row level security;
alter table public.article_series_chapters enable row level security;

create policy series_public on public.article_series for select using (public.series_is_public(id));
create policy series_editor_read on public.article_series for select to authenticated using (public.series_can_manage(id));
create policy series_create on public.article_series for insert to authenticated with check (
  owner_id = auth.uid() and status = 'draft' and version = 0 and not public.is_demo_account() and exists (
    select 1 from public.users where id = auth.uid()
    and roles && array['author','reviewer','admin','owner']::text[]));
create policy series_update on public.article_series for update to authenticated
  using (public.series_can_manage(id) and not public.is_demo_account())
  with check ((owner_id = auth.uid() or public.series_is_elevated()) and not public.is_demo_account());
create policy series_delete on public.article_series for delete to authenticated
  using (public.series_can_manage(id) and not public.is_demo_account());
-- The stable slug, ownership and reorder version cannot be changed through
-- PostgREST, even by someone who can edit the other series fields.
revoke update on public.article_series from authenticated;
grant update (title, description, cover_image, status, updated_at) on public.article_series to authenticated;

create policy series_translation_public on public.article_series_translations for select using (public.series_is_public(series_id));
create policy series_translation_editor_read on public.article_series_translations for select to authenticated using (public.series_can_manage(series_id));
create policy series_translation_write on public.article_series_translations for all to authenticated
  using (public.series_can_manage(series_id) and not public.is_demo_account())
  with check (public.series_can_manage(series_id) and not public.is_demo_account());
-- No public chapter policy: direct PostgREST reads must not reveal positions,
-- draft IDs or counts. Public application reads explicitly filter eligibility.
create policy series_chapter_editor_read on public.article_series_chapters for select to authenticated
  using (public.series_can_manage(series_id));

create function public.replace_series_chapters(p_series_id bigint, p_version bigint, p_article_ids bigint[])
returns bigint language plpgsql security definer set search_path = public as $$
declare current_version bigint; elevated boolean; new_version bigint;
begin
  if auth.uid() is null or public.is_demo_account() or not public.series_can_manage(p_series_id) then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  select version into current_version from public.article_series where id = p_series_id for update;
  if current_version is null then raise exception 'not found' using errcode = 'P0002'; end if;
  if current_version <> p_version then raise exception 'stale version' using errcode = '40001'; end if;
  if p_article_ids is null or cardinality(p_article_ids) > 500 or array_position(p_article_ids, null) is not null
    or cardinality(p_article_ids) <> (select count(distinct x) from unnest(p_article_ids) x) then
    raise exception 'invalid chapters' using errcode = '22023';
  end if;
  elevated := public.series_is_elevated();
  -- Adding, removing or moving another author's article is privileged. An
  -- unchanged chapter can remain when the owner appends their own work.
  if not elevated and exists (
    select 1 from public.articles a
    left join public.article_series_chapters old on old.article_id = a.id and old.series_id = p_series_id
    left join unnest(p_article_ids) with ordinality desired(id, position) on desired.id = a.id
    where (old.article_id is not null or desired.id is not null)
      and a.author_id is distinct from auth.uid()
      and old.position is distinct from desired.position
  ) then
    raise exception 'forbidden article' using errcode = '42501';
  end if;
  if (select count(*) from public.articles where id = any(p_article_ids)) <> cardinality(p_article_ids) then
    raise exception 'article not found' using errcode = '22023';
  end if;
  if exists (select 1 from public.article_series_chapters where article_id = any(p_article_ids) and series_id <> p_series_id) then
    raise exception 'article already assigned' using errcode = '23505';
  end if;
  delete from public.article_series_chapters where series_id = p_series_id;
  insert into public.article_series_chapters(series_id, article_id, position)
    select p_series_id, id, ordinality::integer from unnest(p_article_ids) with ordinality as items(id, ordinality);
  update public.article_series set version = version + 1, updated_at = now() where id = p_series_id returning version into new_version;
  return new_version;
end $$;
revoke all on function public.replace_series_chapters(bigint, bigint, bigint[]) from public;
grant execute on function public.replace_series_chapters(bigint, bigint, bigint[]) to authenticated;

create function public.public_series_sitemap()
returns table (slug text, updated_at timestamptz, has_greek boolean)
language sql stable security definer set search_path = public as $$
  select s.slug, s.updated_at, exists (
    select 1 from public.article_series_translations t
    where t.series_id = s.id and t.locale = 'el' and length(trim(t.title)) > 0
  ) from public.article_series s where public.series_is_public(s.id)
$$;
revoke all on function public.public_series_sitemap() from public, anon, authenticated;
grant execute on function public.public_series_sitemap() to service_role;
