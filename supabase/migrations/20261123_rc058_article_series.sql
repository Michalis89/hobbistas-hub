-- 20261123_rc058_article_series.sql
-- Purpose: article series. An ordered, optional grouping of existing articles
-- and reviews from any hobby category, with an optional Greek translation.
--
-- Data model:
--   - Membership lives in its own table, separate from articles. An article is
--     in at most one series. Deleting a series never deletes its articles;
--     deleting an article removes it from its series; deleting the owner's
--     account keeps the series (owner_id becomes NULL) for elevated editors.
--   - Chapter lists are only written through replace_series_chapters(), one
--     transaction with an optimistic version check.
--
-- Authorization mirrors src/lib/articles/seriesAccess.ts and reuses the
-- existing role helper public.has_any_role():
--   - create:     author, reviewer, admin, owner (the article-creation roles)
--   - manage all: admin, owner, moderator (Studio's "manage all content")
--   - manage own: the owner, only while they still hold an editorial role
--   - chapters:   a non-elevated owner may add, remove and reorder their own
--                 articles; other authors' chapters must stay in the series in
--                 the same relative order.
--
-- Exposure: anon has no access to these tables. Public pages read through the
-- server (service role) and filter publication state explicitly, so draft
-- chapters, their ids, titles, positions and counts are never served.
--
-- Conflicts: a stale version raises SQLSTATE PT409, which PostgREST returns as
-- HTTP 409; assigning an article that is already in another series raises
-- 23505 (also 409). Neither is retried automatically.
--
-- Re-runnable. Not destructive: no existing table or row is changed.

begin;

-- 0. Preconditions ---------------------------------------------------------
do $$
begin
  if to_regprocedure('public.has_any_role(text[])') is null then
    raise exception 'rc058_article_series: public.has_any_role(text[]) is required';
  end if;
  if to_regprocedure('public.is_demo_account()') is null then
    raise exception 'rc058_article_series: public.is_demo_account() is required';
  end if;
end $$;

-- 1. Tables ----------------------------------------------------------------
create table if not exists public.article_series (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text not null check (length(trim(title)) > 0),
  description text,
  cover_image text check (cover_image is null or cover_image ~ '^https://'),
  status text not null default 'draft' check (status in ('draft', 'published')),
  owner_id uuid references public.users(id) on delete set null,
  version bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists article_series_owner_id_idx on public.article_series (owner_id);

create table if not exists public.article_series_translations (
  series_id bigint not null references public.article_series(id) on delete cascade,
  locale text not null check (locale = 'el'),
  title text not null check (length(trim(title)) > 0),
  description text,
  primary key (series_id, locale)
);

create table if not exists public.article_series_chapters (
  series_id bigint not null references public.article_series(id) on delete cascade,
  article_id bigint not null unique references public.articles(id) on delete cascade,
  position integer not null check (position > 0),
  primary key (series_id, article_id),
  unique (series_id, position)
);

-- 2. Authorization helpers -------------------------------------------------
create or replace function public.series_can_create()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select public.has_any_role(array['author', 'reviewer', 'admin', 'owner']);
$$;

create or replace function public.series_can_manage_all()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select public.has_any_role(array['admin', 'owner', 'moderator']);
$$;

create or replace function public.series_can_manage(p_series_id bigint)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.article_series s
    where s.id = p_series_id
      and (
        public.series_can_manage_all()
        or (s.owner_id = (select auth.uid()) and public.series_can_create())
      )
  );
$$;

-- True when the series is published and has at least one publicly visible
-- chapter. Used by the sitemap RPC only.
create or replace function public.series_is_public(p_series_id bigint)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.article_series s
    join public.article_series_chapters c on c.series_id = s.id
    join public.articles a on a.id = c.article_id
    where s.id = p_series_id
      and s.status = 'published'
      and a.status = 'published'
      and (a.published_at is null or a.published_at <= now())
  );
$$;

-- The helpers are called by RLS policies, which run as the caller, so
-- authenticated keeps EXECUTE. Nobody else needs them.
revoke all on function public.series_can_create() from public, anon;
revoke all on function public.series_can_manage_all() from public, anon;
revoke all on function public.series_can_manage(bigint) from public, anon;
grant execute on function public.series_can_create() to authenticated;
grant execute on function public.series_can_manage_all() to authenticated;
grant execute on function public.series_can_manage(bigint) to authenticated;
revoke all on function public.series_is_public(bigint) from public, anon, authenticated;

-- 3. Row level security ----------------------------------------------------
alter table public.article_series enable row level security;
alter table public.article_series_translations enable row level security;
alter table public.article_series_chapters enable row level security;

-- Earlier drafts of this migration created public read policies; drop them by
-- name in case one was applied to a development database.
drop policy if exists series_public on public.article_series;
drop policy if exists series_translation_public on public.article_series_translations;

drop policy if exists series_editor_read on public.article_series;
-- Policies on article_series test the row's own owner_id instead of looking the
-- row up through series_can_manage(): a STABLE lookup cannot see a row that the
-- same statement just inserted, which would break INSERT ... RETURNING.
create policy series_editor_read on public.article_series
  for select to authenticated
  using (public.series_can_manage_all() or (owner_id = (select auth.uid()) and public.series_can_create()));

drop policy if exists series_create on public.article_series;
create policy series_create on public.article_series
  for insert to authenticated
  with check (
    owner_id = (select auth.uid())
    and status = 'draft'
    and version = 0
    and public.series_can_create()
    and not public.is_demo_account()
  );

drop policy if exists series_update on public.article_series;
create policy series_update on public.article_series
  for update to authenticated
  using ((public.series_can_manage_all() or (owner_id = (select auth.uid()) and public.series_can_create())) and not public.is_demo_account())
  with check ((public.series_can_manage_all() or (owner_id = (select auth.uid()) and public.series_can_create())) and not public.is_demo_account());

drop policy if exists series_delete on public.article_series;
create policy series_delete on public.article_series
  for delete to authenticated
  using ((public.series_can_manage_all() or (owner_id = (select auth.uid()) and public.series_can_create())) and not public.is_demo_account());

drop policy if exists series_translation_editor_read on public.article_series_translations;
create policy series_translation_editor_read on public.article_series_translations
  for select to authenticated
  using (public.series_can_manage(series_id));

drop policy if exists series_translation_write on public.article_series_translations;
create policy series_translation_write on public.article_series_translations
  for all to authenticated
  using (public.series_can_manage(series_id) and not public.is_demo_account())
  with check (public.series_can_manage(series_id) and not public.is_demo_account());

-- Chapters: read for managers only; no write policy at all. Writes go through
-- replace_series_chapters().
drop policy if exists series_chapter_editor_read on public.article_series_chapters;
create policy series_chapter_editor_read on public.article_series_chapters
  for select to authenticated
  using (public.series_can_manage(series_id));

-- 4. Table privileges ------------------------------------------------------
revoke all on table public.article_series from anon;
revoke all on table public.article_series_translations from anon;
revoke all on table public.article_series_chapters from anon;

-- The slug is stable, and ownership and the chapter version are never set
-- through the Data API.
revoke update on table public.article_series from authenticated;
grant update (title, description, cover_image, status, updated_at)
  on table public.article_series to authenticated;

revoke insert, update, delete, truncate on table public.article_series_chapters from authenticated;

-- 5. Chapter replacement ---------------------------------------------------
create or replace function public.replace_series_chapters(
  p_series_id bigint,
  p_version bigint,
  p_article_ids bigint[]
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  current_version bigint;
  new_version bigint;
  old_foreign bigint[];
  new_foreign bigint[];
begin
  if caller is null or public.is_demo_account() or not public.series_can_manage(p_series_id) then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  if p_article_ids is null
     or cardinality(p_article_ids) > 500
     or array_position(p_article_ids, null) is not null
     or cardinality(p_article_ids) <> (select count(distinct x) from unnest(p_article_ids) x) then
    raise exception 'invalid chapters' using errcode = '22023';
  end if;

  -- Serialises concurrent edits of the same series.
  select s.version into current_version
  from public.article_series s
  where s.id = p_series_id
  for update;

  if current_version is null then
    raise exception 'series not found' using errcode = 'P0002';
  end if;
  if current_version <> p_version then
    raise exception 'stale version' using errcode = 'PT409';
  end if;

  if not public.series_can_manage_all() then
    -- Other authors' chapters (including articles whose author is gone, and
    -- ids that do not exist) must be exactly the same list, in the same
    -- relative order, before and after. The caller's own articles are free.
    -- Unknown ids count as foreign, so the answer does not reveal whether an
    -- article id exists.
    select coalesce(array_agg(c.article_id order by c.position), '{}')
      into old_foreign
    from public.article_series_chapters c
    left join public.articles a on a.id = c.article_id
    where c.series_id = p_series_id
      and a.author_id is distinct from caller;

    select coalesce(array_agg(d.id order by d.ord), '{}')
      into new_foreign
    from unnest(p_article_ids) with ordinality as d(id, ord)
    left join public.articles a on a.id = d.id
    where a.author_id is distinct from caller;

    if old_foreign is distinct from new_foreign then
      raise exception 'forbidden article' using errcode = '42501';
    end if;
  end if;

  if (select count(*) from public.articles a where a.id = any (p_article_ids))
     <> cardinality(p_article_ids) then
    raise exception 'article not found' using errcode = '22023';
  end if;

  if exists (
    select 1 from public.article_series_chapters c
    where c.article_id = any (p_article_ids) and c.series_id <> p_series_id
  ) then
    raise exception 'article already in another series' using errcode = '23505';
  end if;

  delete from public.article_series_chapters where series_id = p_series_id;

  -- A concurrent assignment of the same article to another series waits on
  -- the unique index here and then fails with 23505.
  insert into public.article_series_chapters (series_id, article_id, position)
  select p_series_id, d.id, d.ord::integer
  from unnest(p_article_ids) with ordinality as d(id, ord);

  update public.article_series
     set version = version + 1,
         updated_at = now()
   where id = p_series_id
  returning version into new_version;

  return new_version;
end;
$$;

revoke all on function public.replace_series_chapters(bigint, bigint, bigint[]) from public, anon;
grant execute on function public.replace_series_chapters(bigint, bigint, bigint[]) to authenticated;

-- 6. Sitemap ---------------------------------------------------------------
create or replace function public.public_series_sitemap()
returns table (slug text, updated_at timestamptz, has_greek boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select s.slug,
         s.updated_at,
         exists (
           select 1 from public.article_series_translations t
           where t.series_id = s.id and t.locale = 'el' and length(trim(t.title)) > 0
         )
  from public.article_series s
  where public.series_is_public(s.id);
$$;

revoke all on function public.public_series_sitemap() from public, anon, authenticated;
grant execute on function public.public_series_sitemap() to service_role;

commit;
